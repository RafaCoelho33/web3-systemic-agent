class SnapshotGovernanceConnector:
    """
    Asynchronous connector for Snapshot GraphQL governance data with automatic fallback
    to realistic curated proposals.
    """

    SNAPSHOT_GRAPHQL_URL: str = "https://hub.snapshot.org/graphql"
    DEFAULT_SPACES: List[str] = ["arbitrumfoundation.eth", "aavedao.eth", "ens.eth"]

    def __init__(
        self,
        graphql_url: Optional[str] = None,
        default_chain_id: ChainId = ChainId.BASE_SEPOLIA,
        timeout: float = 8.0,
    ):
        self.graphql_url = graphql_url or self.SNAPSHOT_GRAPHQL_URL
        self.default_chain_id = default_chain_id
        self.timeout = timeout

    async def fetch_proposals(
        self,
        spaces: Optional[List[str]] = None,
        limit: int = 3,
        state: str = "all",
        use_curated_fallback: bool = True,
    ) -> List[GovernanceProposal]:
        """
        Fetches recent DAO proposals from Snapshot GraphQL API.
        Falls back to curated DAO proposals if unreachable or on error.
        """
        target_spaces = spaces if spaces is not None else self.DEFAULT_SPACES
        query = """
        query GetProposals($limit: Int!, $spaces: [String!]) {
          proposals(first: $limit, where: {space_in: $spaces}) {
            id
            title
            body
            author
            state
            created
            space {
              id
            }
          }
        }
        """
        variables = {"limit": limit, "spaces": target_spaces}
        try:
            async with httpx.AsyncClient(timeout=self.timeout) as client:
                resp = await client.post(
                    self.graphql_url,
                    json={"query": query, "variables": variables},
                )
            if resp.status_code != 200:
                if use_curated_fallback:
                    logger.warning(
                        f"Snapshot API returned status {resp.status_code}; using curated fallback"
                    )
                    return get_curated_dao_proposals(self.default_chain_id, limit=limit)
                resp.raise_for_status()

            data = resp.json().get("data", {})
            proposals_raw = data.get("proposals") if isinstance(data, dict) else None
            if not proposals_raw:
                if use_curated_fallback:
                    return get_curated_dao_proposals(self.default_chain_id, limit=limit)
                return []

            results: List[GovernanceProposal] = []
            for item in proposals_raw[:limit]:
                space_id = (
                    item.get("space", {}).get("id", "")
                    if isinstance(item.get("space"), dict)
                    else str(item.get("space") or "")
                )
                body = item.get("body") or ""
                hints = extract_onchain_hints(body)
                results.append(
                    GovernanceProposal(
                        proposal_id=str(item.get("id", "")),
                        space_id=space_id,
                        title=str(item.get("title", "")),
                        body=body,
                        author=str(item.get("author", "0x0000000000000000000000000000000000000000")),
                        state=str(item.get("state", "active")),
                        created=int(item.get("created", 0)),
                        target_address=hints["target_address"],
                        calldata=hints["calldata"],
                        tx_value_wei=0,
                        chain_id=self.default_chain_id,
                    )
                )
            return results
        except Exception as exc:
            if use_curated_fallback:
                logger.warning(
                    f"Snapshot GraphQL request failed ({exc}); using curated fallback"
                )
                return get_curated_dao_proposals(self.default_chain_id, limit=limit)
            raise

    def proposal_to_rule_payload(
        self,
        proposal: GovernanceProposal,
        policy_prompt: Optional[str] = None,
        risk_threshold: float = 7.0,
    ) -> ConditionRulePayload:
        """
        Converts a GovernanceProposal into an actionable ConditionRulePayload for the agent engine.
        """
        return ConditionRulePayload(
            rule_id=f"gov-{proposal.space_id}-{proposal.proposal_id[:12]}",
            chain_id=proposal.chain_id,
            deterministic=DeterministicCondition(
                target_address=proposal.target_address,
                min_value_wei=0,
                required_function_selectors=None,
                check_native_balance=False,
            ),
            semantic=SemanticCondition(
                enabled=True,
                policy_prompt=policy_prompt
                or (
                    "Audit DAO governance proposal for hidden privilege escalation, "
                    "unverified contract upgrades, or discrepancies between proposal text and on-chain calldata."
                ),
                risk_threshold=risk_threshold,
            ),
            context_metadata={
                "proposal_id": proposal.proposal_id,
                "space_id": proposal.space_id,
                "proposal_title": proposal.title,
                "proposal_description": f"{proposal.title}\n\n{proposal.body}",
                "calldata": proposal.calldata,
                "tx_value_wei": proposal.tx_value_wei,
            },
        )

    async def audit_proposals(
        self,
        engine: ConditionAgentEngine,
        proposals: Optional[List[GovernanceProposal]] = None,
        spaces: Optional[List[str]] = None,
        limit: int = 3,
    ) -> List[GovernanceAuditReport]:
        """
        Executes end-to-end security audits across governance proposals.
        """
        target_proposals = proposals
        if target_proposals is None:
            target_proposals = await self.fetch_proposals(spaces=spaces, limit=limit)

        reports: List[GovernanceAuditReport] = []
        for prop in target_proposals:
            payload = self.proposal_to_rule_payload(prop)
            resp = await engine.process_rule(payload, source="governance_listener")

            if resp.semantic_Evaluation is None:
                alert_level: Literal["CRITICAL", "WARNING", "INFO"] = "INFO"
            elif resp.semantic_Evaluation.recommended_action == "REJECT":
                alert_level = "CRITICAL"
            elif resp.semantic_Evaluation.recommended_action == "MANUAL_REVIEW":
                alert_level = "WARNING"
            else:
                alert_level = "INFO"

            reports.append(
                GovernanceAuditReport(
                    proposal=prop,
                    rule_id=payload.rule_id,
                    agent_response=resp,
                    alert_level=alert_level,
                )
            )

        return reports
