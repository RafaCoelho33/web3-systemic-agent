class SnapshotGovernanceConnector:
    """
    Asynchronous connector for Snapshot GraphQL governance data with automatic fallback
    to realistic curated proposals.
    """

    SNAPSHOT_GRAPHQL_URL: str = "https://hub.snapshot.org/graphql"
    DEFAULT_SPACES: List[str] = ["arbitrumfoundation.eth", "aavedao.eth", "ens.eth"]

    def __init__(
        self,
        graphql_url: Optional[str] = None,
        default_chain_id: ChainId = ChainId.BASE_SEPOLIA,
        timeout: float = 8.0,
    ):
        self.graphql_url = graphql_url or self.SNAPSHOT_GRAPHQL_URL
        self.default_chain_id = default_chain_id
        self.timeout = timeout

    async def fetch_proposals(
        self,
        spaces: Optional[List[str]] = None,
        limit: int = 3,
        state: str = "all",
        use_curated_fallback: bool = True,
    ) -> List[GovernanceProposal]:
        """
        Fetches recent DAO proposals from Snapshot GraphQL API.
        Falls back to curated DAO proposals if unreachable or on error.
        """
        target_spaces = spaces if spaces is not None else self.DEFAULT_SPACES
        query = """
        query GetProposals($limit: Int!, $spaces: [String!]) {
          proposals(first: $limit, where: {space_in: $spaces}) {
            id
            title
            body
            author
            state
            created
            space {
              id
            }
          }
        }
        """
        variables = {"limit": limit, "spaces": target_spaces}
        try:
            async with httpx.AsyncClient(timeout=self.timeout) as client:
                resp = await client.post(
                    self.graphql_url,
                    json={"query": query, "variables": variables},
                )
            if resp.status_code != 200:
                if use_curated_fallback:
                    logger.warning(
                        f"Snapshot API returned status {resp.status_code}; using curated fallback"
                    )
                    return get_curated_dao_proposals(self.default_chain_id, limit=limit)
                resp.raise_for_status()

            data = resp.json().get("data", {})
            proposals_raw = data.get("proposals") if isinstance(data, dict) else None
            if not proposals_raw:
                if use_curated_fallback:
                    return get_curated_dao_proposals(self.default_chain_id, limit=limit)
                return []

            results: List[GovernanceProposal] = []
            for item in proposals_raw[:limit]:
                space_id = (
                    item.get("space", {}).get("id", "")
                    if isinstance(item.get("space"), dict)
                    else str(item.get("space") or "")
                )
                body = item.get("body") or ""
                hints = extract_onchain_hints(body)
                results.append(
                    GovernanceProposal(
                        proposal_id=str(item.get("id", "")),
                        space_id=space_id,
                        title=str(item.get("title", "")),
                        body=body,
                        author=str(item.get("author", "0x0000000000000000000000000000000000000000")),
                        state=str(item.get("state", "active")),
                        created=int(item.get("created", 0)),
                        target_address=hints["target_address"],
                        calldata=hints["calldata"],
                        tx_value_wei=0,
                        chain_id=self.default_chain_id,
                    )
                )
            return results
        except Exception as exc:
            if use_curated_fallback:
                logger.warning(
                    f"Snapshot GraphQL request failed ({exc}); using curated fallback"
                )
                return get_curated_dao_proposals(self.default_chain_id, limit=limit)
            raise

    def proposal_to_rule_payload(
        self,
        proposal: GovernanceProposal,
        policy_prompt: Optional[str] = None,
        risk_threshold: float = 7.0,
    ) -> ConditionRulePayload:
        """
        Converts a GovernanceProposal into an actionable ConditionRulePayload for the agent engine.
        """
        return ConditionRulePayload(
            rule_id=f"gov-{proposal.space_id}-{proposal.proposal_id[:12]}",
            chain_id=proposal.chain_id,
            deterministic=DeterministicCondition(
                target_address=proposal.target_address,
                min_value_wei=0,
                required_function_selectors=None,
                check_native_balance=False,
            ),
            semantic=SemanticCondition(
                enabled=True,
                policy_prompt=policy_prompt
                or (
                    "Audit DAO governance proposal for hidden privilege escalation, "
                    "unverified contract upgrades, or discrepancies between proposal text and on-chain calldata."
                ),
                risk_threshold=risk_threshold,
            ),
            context_metadata={
                "proposal_id": proposal.proposal_id,
                "space_id": proposal.space_id,
                "proposal_title": proposal.title,
                "proposal_description": f"{proposal.title}\n\n{proposal.body}",
                "calldata": proposal.calldata,
                "tx_value_wei": proposal.tx_value_wei,
            },
        )

    async def audit_proposals(
        self,
        engine: ConditionAgentEngine,
        proposals: Optional[List[GovernanceProposal]] = None,
        spaces: Optional[List[str]] = None,
        limit: int = 3,
    ) -> List[GovernanceAuditReport]:
        """
        Executes end-to-end security audits across governance proposals.
        """
        target_proposals = proposals
        if target_proposals is None:
            target_proposals = await self.fetch_proposals(spaces=spaces, limit=limit)

        reports: List[GovernanceAuditReport] = []
        for prop in target_proposals:
            payload = self.proposal_to_rule_payload(prop)
            resp = await engine.process_rule(payload, source="governance_listener")

            if resp.semantic_Evaluation is None:
                alert_level: Literal["CRITICAL", "WARNING", "INFO"] = "INFO"
            elif resp.semantic_Evaluation.recommended_action == "REJECT":
                alert_level = "CRITICAL"
            elif resp.semantic_Evaluation.recommended_action == "MANUAL_REVIEW":
                alert_level = "WARNING"
            else:
                alert_level = "INFO"

            reports.append(
                GovernanceAuditReport(
                    proposal=prop,
                    rule_id=payload.rule_id,
                    agent_response=resp,
                    alert_level=alert_level,
                )
            )

        return reports


class WebhookAlertDispatcher:
    """
    Dispatches automated governance security alerts to external webhooks
    (Discord, Slack, or generic HTTP endpoints) with x402 monetization links.
    """

    def __init__(
        self,
        webhook_url: Optional[str] = None,
        public_api_url: Optional[str] = None,
        price_usdc: float = 0.01,
        timeout: float = 10.0,
        client: Optional[httpx.AsyncClient] = None,
    ):
        self.webhook_url = (webhook_url or os.getenv("ALERT_WEBHOOK_URL") or "").strip() or None
        self.public_api_url = (public_api_url or os.getenv("PUBLIC_API_URL") or "http://localhost:8000").rstrip("/")
        self.price_usdc = price_usdc
        self.timeout = timeout
        self.client = client

    def format_alert_payload(self, report: GovernanceAuditReport) -> Dict[str, Any]:
        """
        Formats a governance audit report into Discord/Slack/generic compatible JSON payload
        with x402 monetization links.
        """
        prop = report.proposal
        sem = report.agent_response.semantic_Evaluation
        decision = sem.recommended_action if sem else "SKIPPED"
        risk_score = sem.risk_score if sem else 0.0
        summary = sem.summary if sem else "Stage 1 filtered"
        flagged = list(sem.flagged_issues) if sem else []

        audit_endpoint = f"{self.public_api_url}/evaluate"
        content_text = (
            f"🚨 **GOVERNANCE SECURITY ALERT [{report.alert_level}]** 🚨\n"
            f"• **Space**: `{prop.space_id}`\n"
            f"• **Title**: {prop.title}\n"
            f"• **Decision**: `{decision}` (Risk Score: {risk_score:.1f})\n"
            f"• **Target Address**: `{prop.target_address}`\n"
            f"• **Summary**: {summary}\n"
            f"💳 **x402 Monetized Audit**: `{audit_endpoint}` (${self.price_usdc:.4f} USDC)"
        )

        color_map = {
            "CRITICAL": 0xFF0000,
            "WARNING": 0xFFA500,
            "INFO": 0x3498DB,
        }
        embed_color = color_map.get(report.alert_level, 0x808080)

        embeds = [
            {
                "title": f"[{report.alert_level}] {prop.space_id}: {prop.title[:100]}",
                "description": summary[:1000] if summary else "",
                "color": embed_color,
                "fields": [
                    {"name": "Decision", "value": str(decision), "inline": True},
                    {"name": "Risk Score", "value": f"{risk_score:.1f}", "inline": True},
                    {"name": "Target Address", "value": str(prop.target_address), "inline": False},
                    {
                        "name": "Flagged Issues",
                        "value": "\n".join(f"- {i}" for i in flagged) if flagged else "None",
                        "inline": False,
                    },
                    {
                        "name": "x402 Paid Audit",
                        "value": f"{audit_endpoint} (${self.price_usdc:.4f} USDC)",
                        "inline": False,
                    },
                ],
            }
        ]

        return {
            "content": content_text,
            "text": content_text,
            "embeds": embeds,
            "alert_level": report.alert_level,
            "proposal_id": prop.proposal_id,
            "space_id": prop.space_id,
            "decision": decision,
            "risk_score": risk_score,
            "flagged_issues": flagged,
            "x402_audit_endpoint": audit_endpoint,
            "price_usdc": self.price_usdc,
        }

    async def dispatch_alert(self, report: GovernanceAuditReport) -> bool:
        """
        Sends formatted alert payload to webhook URL.
        Returns True on HTTP 2xx, False otherwise without raising unhandled exceptions.
        """
        if not self.webhook_url:
            return False

        payload = self.format_alert_payload(report)
        try:
            if self.client:
                resp = await self.client.post(self.webhook_url, json=payload)
            else:
                async with httpx.AsyncClient(timeout=self.timeout) as client:
                    resp = await client.post(self.webhook_url, json=payload)

            if 200 <= resp.status_code < 300:
                return True
            else:
                logger.warning(
                    f"Webhook dispatch failed with HTTP {resp.status_code}: {resp.text}"
                )
                return False
        except Exception as exc:
            logger.warning(f"Webhook dispatch exception: {exc}")
            return False

    async def dispatch_batch(
        self,
        reports: List[GovernanceAuditReport],
        min_alert_level: str = "WARNING",
    ) -> int:
        """
        Dispatches alerts for all reports meeting or exceeding min_alert_level.
        Returns the count of successfully delivered webhook requests.
        """
        min_order = ALERT_SEVERITY_ORDER.get(min_alert_level.upper(), 2)
        matching_reports = [
            r for r in reports
            if ALERT_SEVERITY_ORDER.get(r.alert_level, 0) >= min_order
        ]
        sent_count = 0
        for r in matching_reports:
            success = await self.dispatch_alert(r)
            if success:
                sent_count += 1
        return sent_count

